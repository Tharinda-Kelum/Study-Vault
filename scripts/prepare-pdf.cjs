const fs = require('node:fs');
const path = require('node:path');
const root = path.dirname(require.resolve('pdfjs-dist/package.json'));
const moduleUrl = name => 'data:text/javascript;base64,' + fs.readFileSync(path.join(root, 'legacy', 'build', name)).toString('base64');
fs.mkdirSync('src/generated', { recursive: true });
fs.writeFileSync('src/generated/pdfModules.js', '// Generated by scripts/prepare-pdf.cjs. PDF.js is licensed under Apache-2.0.\n' +
  'export const pdfModule=' + JSON.stringify(moduleUrl('pdf.min.mjs')) + ';\n' +
  'export const workerModule=' + JSON.stringify(moduleUrl('pdf.worker.min.mjs')) + ';\n');
fs.copyFileSync(path.join(root, 'LICENSE'), 'src/generated/PDFJS-LICENSE');
